-- ジャンルマスターを canonical な 25 件に固定する。
--
-- 経緯：0008 で「INSERT/UPDATE 凍結 + デフォルト 25 件 seed」を入れた直後の
-- 本番では、ユーザーが過去に追加した旧ジャンル（しゃぶしゃぶ / 焼肉 / ハンバーグ）が
-- 残っていた。admin が Studio 上で restaurants の付け替えと旧ジャンル DELETE を
-- 実施し、本番は 25 件のみになった。その正解状態をコード（migration）でも
-- ソース化することで、以降どの環境でも `supabase db reset` 後に同じ 25 件で揃う。
--
-- このマイグレーションは idempotent：
--   - 本番：旧 3 件は手動で消し済 → DELETE は 0 行
--   - 新規環境：0008 が 25 件のみ seed する → DELETE は 0 行
--   - 他環境で旧データが残っている場合：参照中の restaurants があれば
--     FK (ON DELETE RESTRICT) で失敗するので、先にアプリ側で付け替えること
